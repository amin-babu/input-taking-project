let firstValue = parseInt(prompt('First Value:'));
let secondValue = parseInt(prompt('Second Value:'));

document.write(`Summation: ${firstValue + secondValue} <br/>`);
document.write(`Subtraction: ${firstValue - secondValue} <br/>`);
document.write(`Multiplication: ${firstValue * secondValue} <br/>`);
document.write(`Division: ${firstValue / secondValue} <br/>`);
document.write(`Exponential: ${firstValue ** secondValue} <br/>`);